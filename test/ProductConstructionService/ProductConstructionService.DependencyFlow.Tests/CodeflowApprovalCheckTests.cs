using AwesomeAssertions;
using Maestro.Data;
using Maestro.Data.Models;
using Maestro.DataProviders;
using Maestro.WorkItems;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Moq;
using NUnit.Framework;
using ProductConstructionService.DependencyFlow.PullRequestUpdaters;
using ProductConstructionService.DependencyFlow.WorkItems;

namespace ProductConstructionService.DependencyFlow.Tests;

/// <summary>
/// Covers the auto-approval behavior of forward-flow code flow PRs. This behavior is
/// security-sensitive because a passing check produces an approving review, so we assert that:
/// an approval is requested only when the PR's diff matches the expected source diff; the approval
/// is pinned to the PR head SHA that was checked (so a later push isn't implicitly approved);
/// a PR containing any commit not generated by the service is never approved.
/// </summary>
[TestFixture, NonParallelizable]
internal class CodeflowApprovalCheckTests : UpdateAssetsPullRequestUpdaterTests
{
    private const string PreviousSourceSha = "previous.source.sha";

    [Test]
    public async Task ApprovesPullRequestWhenTheDiffMatches()
    {
        GivenATestChannel();
        GivenACodeFlowSubscription(
            new SubscriptionPolicy
            {
                Batchable = false,
                UpdateFrequency = UpdateFrequency.EveryBuild,
            },
            autoApprove: true);
        Build build = GivenANewBuild(true);

        GivenAnOpenInProgressCodeFlowPullRequest(build);
        GivenTheTargetBranchRequiresLastPushApproval(true);
        GivenThePullRequestOnlyHasBotCommits(VmrPullRequestUrl);
        GivenTheForwardFlowMatchesTheSourceDiff(true);

        var beforeApproval = DateTime.UtcNow;
        var outcomes = await WhenRunCodeflowApprovalCheckAsyncIsCalled(GivenACodeflowApprovalCheck(build));

        ThenThePullRequestShouldHaveBeenApproved(VmrPullRequestUrl);
        ThenTheInProgressPullRequestWasChecked();
        var outcome = outcomes.Should().ContainSingle().Subject;
        outcome.Type.Should().Be(SubscriptionOutcomeType.Approved);
        outcome.SubscriptionId.Should().Be(Subscription.Id);
        outcome.BuildId.Should().Be(build.Id);
        outcome.PrUrl.Should().Be(VmrPullRequestUrl);
        outcome.Message.Should().Be($"Automatically approved pull request at commit {InProgressPrHeadBranchSha}");
        outcome.OperationId.Should().NotBeNullOrEmpty();
        outcome.Date.Should().BeOnOrAfter(beforeApproval).And.BeOnOrBefore(DateTime.UtcNow);
    }

    [Test]
    public async Task DoesNotApprovePullRequestWhenTheDiffDoesNotMatch()
    {
        GivenATestChannel();
        GivenACodeFlowSubscription(
            new SubscriptionPolicy
            {
                Batchable = false,
                UpdateFrequency = UpdateFrequency.EveryBuild,
            },
            autoApprove: true);
        Build build = GivenANewBuild(true);

        GivenAnOpenInProgressCodeFlowPullRequest(build);
        GivenTheTargetBranchRequiresLastPushApproval(true);
        GivenThePullRequestOnlyHasBotCommits(VmrPullRequestUrl);
        GivenTheForwardFlowMatchesTheSourceDiff(false);
        GivenTheMismatchCommentCanBePosted();

        var outcomes = await WhenRunCodeflowApprovalCheckAsyncIsCalled(GivenACodeflowApprovalCheck(build));

        outcomes.Should().BeEmpty();
        ThenThePullRequestShouldNotHaveBeenApproved();
        ThenTheMismatchCommentWasPosted();
        ThenTheInProgressPullRequestWasChecked();
    }

    [Test]
    public async Task DoesNotApprovePullRequestWhenItContainsNonServiceCommits()
    {
        GivenATestChannel();
        GivenACodeFlowSubscription(
            new SubscriptionPolicy
            {
                Batchable = false,
                UpdateFrequency = UpdateFrequency.EveryBuild,
            },
            autoApprove: true);
        Build build = GivenANewBuild(true);

        GivenAnOpenInProgressCodeFlowPullRequest(build);
        GivenTheTargetBranchRequiresLastPushApproval(true);
        GivenThePullRequestHasANonServiceCommit(VmrPullRequestUrl);
        GivenTheForwardFlowMatchesTheSourceDiff(true);

        var outcomes = await WhenRunCodeflowApprovalCheckAsyncIsCalled(GivenACodeflowApprovalCheck(build));

        outcomes.Should().BeEmpty();
        ThenThePullRequestShouldNotHaveBeenApproved();
        ThenTheSourceDiffShouldNotHaveBeenVerified();
        ThenTheInProgressPullRequestWasChecked();
    }

    [Test]
    public async Task DoesNotApprovePullRequestWhenLastPushApprovalIsNotRequired()
    {
        GivenATestChannel();
        GivenACodeFlowSubscription(
            new SubscriptionPolicy
            {
                Batchable = false,
                UpdateFrequency = UpdateFrequency.EveryBuild,
            },
            autoApprove: true);
        Build build = GivenANewBuild(true);

        GivenAnOpenInProgressCodeFlowPullRequest(build);
        GivenTheTargetBranchRequiresLastPushApproval(false);

        var outcomes = await WhenRunCodeflowApprovalCheckAsyncIsCalled(GivenACodeflowApprovalCheck(build));

        outcomes.Should().BeEmpty();
        ThenThePullRequestShouldNotHaveBeenApproved();
        ThenTheSourceDiffShouldNotHaveBeenVerified();
        ThenOnlyThePullRequestAndTargetBranchRulesWereChecked();
    }

    [Test]
    public async Task DoesNotRecordApprovalWhenApprovingThePullRequestFails()
    {
        GivenATestChannel();
        GivenACodeFlowSubscription(
            new SubscriptionPolicy
            {
                Batchable = false,
                UpdateFrequency = UpdateFrequency.EveryBuild,
            },
            autoApprove: true);
        Build build = GivenANewBuild(true);

        GivenAnOpenInProgressCodeFlowPullRequest(build);
        GivenTheTargetBranchRequiresLastPushApproval(true);
        GivenThePullRequestOnlyHasBotCommits(VmrPullRequestUrl);
        GivenTheForwardFlowMatchesTheSourceDiff(true);
        PullRequestApprover
            .Setup(x => x.ApprovePullRequestAsync(
                VmrPullRequestUrl,
                InProgressPrHeadBranchSha,
                It.IsAny<string>(),
                It.IsAny<CancellationToken>()))
            .ThrowsAsync(new InvalidOperationException("Approval failed"));

        await Execute(async context =>
        {
            var updater = (CodeFlowPullRequestUpdater)CreatePullRequestActor(context, isCodeflow: true);
            Func<Task> approve = () => updater.RunCodeflowApprovalCheckAsync(
                SqlBarClient.ToClientModelSubscription(Subscription),
                GivenACodeflowApprovalCheck(build),
                CancellationToken.None);

            await approve.Should().ThrowAsync<NonRetriableException>()
                .WithMessage($"Failed to approve pull request {VmrPullRequestUrl}: Approval failed");

            var outcomes = await context.GetRequiredService<BuildAssetRegistryContext>()
                .SubscriptionOutcomes.AsNoTracking().ToListAsync();
            outcomes.Should().BeEmpty();
        });

        ThenTheInProgressPullRequestWasChecked();
    }

    private CodeflowApprovalCheck GivenACodeflowApprovalCheck(Build build)
        => new()
        {
            UpdaterId = GetPullRequestUpdaterId().ToString(),
            SubscriptionId = Subscription.Id,
            PreviousSourceSha = PreviousSourceSha,
            CurrentSourceSha = build.Commit,
            PullRequestUrl = VmrPullRequestUrl,
        };

    private void GivenTheTargetBranchRequiresLastPushApproval(bool required)
        => DarcRemotes[VmrUri]
            .Setup(x => x.IsLastPushApprovalRequiredAsync(VmrUri, TargetBranch))
            .ReturnsAsync(required);

    private void GivenTheMismatchCommentCanBePosted()
        => DarcRemotes[VmrUri]
            .Setup(x => x.CommentPullRequestAsync(
                VmrPullRequestUrl,
                It.Is<string>(comment => comment.Contains("unexpected.txt"))))
            .Returns(Task.CompletedTask);

    private void ThenTheMismatchCommentWasPosted()
        => DarcRemotes[VmrUri].Verify(x => x.CommentPullRequestAsync(
            VmrPullRequestUrl,
            It.Is<string>(comment => comment.Contains("unexpected.txt"))));

    private void ThenTheInProgressPullRequestWasChecked()
    {
        DarcRemotes[VmrUri].Verify(x => x.GetPullRequestAsync(VmrPullRequestUrl), Times.Once);
        DarcRemotes[VmrUri].Verify(
            x => x.IsLastPushApprovalRequiredAsync(VmrUri, TargetBranch),
            Times.Once);
        DarcRemotes[VmrUri].Verify(x => x.GetPullRequestCommitsAsync(VmrPullRequestUrl), Times.Once);
    }

    private void ThenOnlyThePullRequestAndTargetBranchRulesWereChecked()
    {
        DarcRemotes[VmrUri].Verify(x => x.GetPullRequestAsync(VmrPullRequestUrl), Times.Once);
        DarcRemotes[VmrUri].Verify(
            x => x.IsLastPushApprovalRequiredAsync(VmrUri, TargetBranch),
            Times.Once);
        DarcRemotes[VmrUri].Verify(
            x => x.GetPullRequestCommitsAsync(It.IsAny<string>()),
            Times.Never);
    }
}
